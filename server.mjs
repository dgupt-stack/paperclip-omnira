const serviceName = process.env.OMNIRA_SERVICE_NAME || "paperclip";
const publicHost =
  process.env.PAPERCLIP_PUBLIC_HOST ||
  `${serviceName}-k4u67azzg5.app.omnira.dev`;
const publicUrl =
  process.env.PAPERCLIP_AUTH_PUBLIC_BASE_URL || `https://${publicHost}`;
const instanceId = process.env.PAPERCLIP_INSTANCE_ID || "default";
const paperclipHome =
  process.env.PAPERCLIP_HOME || join(homedir(), ".paperclip-omnira");
const configPath = join(
  paperclipHome,
  "instances",
  instanceId,
  "config.json",
);
const cli = join(process.cwd(), "node_modules", "paperclipai", "dist", "index.js");

mkdirSync(paperclipHome, { recursive: true });

function paperclipArgs() {
  return existsSync(configPath)
    ? [cli, "run"]
    : [cli, "onboard", "--yes", "--data-dir", paperclipHome];
}

function paperclipEnvironment({ port, databaseUrl }) {
  return {
    ...process.env,
    HOST: "127.0.0.1",
    PORT: String(port),
    DATABASE_URL: databaseUrl,
    PAPERCLIP_HOME: paperclipHome,
    PAPERCLIP_INSTANCE_ID: instanceId,
    PAPERCLIP_BIND: "custom",
    PAPERCLIP_BIND_HOST: "127.0.0.1",
    PAPERCLIP_DEPLOYMENT_MODE: "authenticated",
    PAPERCLIP_DEPLOYMENT_EXPOSURE:
      process.env.PAPERCLIP_DEPLOYMENT_EXPOSURE || "private",
    PAPERCLIP_AUTH_BASE_URL_MODE: "explicit",
    PAPERCLIP_AUTH_PUBLIC_BASE_URL: publicUrl,
    PAPERCLIP_ALLOWED_HOSTNAMES: [
      publicHost,
      "127.0.0.1",
      "localhost",
    ].join(","),
    BETTER_AUTH_TRUSTED_ORIGINS: publicUrl,
    PAPERCLIP_MIGRATION_AUTO_APPLY: "true",
    PAPERCLIP_DB_BACKUP_ENABLED: "false",
    PAPERCLIP_OPEN_ON_LISTEN: "false",
    PAPERCLIP_NO_BROWSER: "1",
    PAPERCLIP_TELEMETRY_DISABLED: "1",
    DO_NOT_TRACK: "1",
  };
}

function spawnPaperclip(env) {
  return spawn(process.execPath, paperclipArgs(), {
    env,
    stdio: "inherit",
  });
}

function ensureOmniraConfig({ appPort, databaseUrl }) {
  const instanceRoot = join(paperclipHome, "instances", instanceId);
  const envPath = join(instanceRoot, ".env");
  const secretsPath = join(instanceRoot, "secrets", "master.key");
  const storagePath = join(instanceRoot, "data", "storage");
  const backupPath = join(instanceRoot, "data", "backups");
  const logPath = join(instanceRoot, "logs");
  mkdirSync(join(instanceRoot, "secrets"), { recursive: true });
  mkdirSync(storagePath, { recursive: true });

  if (!existsSync(envPath)) {
    writeFileSync(
      envPath,
      `# Paperclip environment variables\n# Generated by paperclip-omnira\nPAPERCLIP_AGENT_JWT_SECRET=${randomBytes(32).toString("hex")}\n`,
      { mode: 0o600 },
    );
  } else if (!/^PAPERCLIP_AGENT_JWT_SECRET=/m.test(readFileSync(envPath, "utf8"))) {
    writeFileSync(
      envPath,
      `${readFileSync(envPath, "utf8").trimEnd()}\nPAPERCLIP_AGENT_JWT_SECRET=${randomBytes(32).toString("hex")}\n`,
      { mode: 0o600 },
    );
  }
  if (!existsSync(secretsPath)) {
    writeFileSync(secretsPath, randomBytes(32).toString("base64"), { mode: 0o600 });
  }

  let existing = {};
  if (existsSync(configPath)) {
    try {
      existing = JSON.parse(readFileSync(configPath, "utf8"));
    } catch {
      existing = {};
    }
  }
  const exposure = process.env.PAPERCLIP_DEPLOYMENT_EXPOSURE || "private";
  const config = {
    ...existing,
    $meta: {
      version: 1,
      updatedAt: new Date().toISOString(),
      source: existing.$meta?.source || "onboard",
    },
    database: {
      ...existing.database,
      mode: "postgres",
      connectionString: databaseUrl,
      embeddedPostgresDataDir: join(instanceRoot, "db"),
      embeddedPostgresPort: 54329,
      backup: {
        enabled: false,
        intervalMinutes: 60,
        retentionDays: 1,
        dir: backupPath,
      },
    },
    logging: {
      mode: existing.logging?.mode || "file",
      logDir: logPath,
    },
    server: {
      ...existing.server,
      deploymentMode: "authenticated",
      exposure,
      bind: "custom",
      customBindHost: "127.0.0.1",
      host: "127.0.0.1",
      port: appPort,
      allowedHostnames: [publicHost, "127.0.0.1", "localhost"],
      serveUi: true,
    },
    auth: {
      ...existing.auth,
      baseUrlMode: "explicit",
      publicBaseUrl: publicUrl,
      disableSignUp: existing.auth?.disableSignUp ?? false,
    },
    telemetry: { enabled: false },
    storage: {
      ...existing.storage,
      provider: existing.storage?.provider || "local_disk",
      localDisk: { baseDir: storagePath },
      s3: {
        ...existing.storage?.s3,
        bucket: "paperclip",
        region: "us-east-1",
        prefix: "",
        forcePathStyle: false,
      },
    },
    secrets: {
      provider: "local_encrypted",
      strictMode: true,
      localEncrypted: { keyFilePath: secretsPath },
    },
  };
  writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`, { mode: 0o600 });
}

async function findFreePort(excluded = new Set()) {
  for (;;) {
    const port = await new Promise((resolve, reject) => {
      const server = createNetServer();
      server.once("error", reject);
      server.listen(0, "127.0.0.1", () => {
        const address = server.address();
        const selected = typeof address === "object" && address ? address.port : 0;
        server.close((error) => (error ? reject(error) : resolve(selected)));
      });
    });
    if (!excluded.has(port)) return port;
  }
}

async function waitForHealth(port, child, timeoutMs = 120_000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (child.exitCode !== null) {
      throw new Error(`Paperclip exited before becoming healthy (code ${child.exitCode})`);
    }
    try {
      const response = await fetch(`http://127.0.0.1:${port}/api/health`);
      if (response.ok) return;
    } catch {
      // Startup can take a while while Paperclip migrates a restored database.
    }
    await new Promise((resolve) => setTimeout(resolve, 500));
  }
  throw new Error("Paperclip did not become healthy within 120 seconds");
}

async function terminateChild(child, timeoutMs = 5_000) {
  if (!child || child.exitCode !== null) return;
  child.kill("SIGTERM");
  await Promise.race([
    new Promise((resolve) => child.once("exit", resolve)),
    new Promise((resolve) => setTimeout(resolve, timeoutMs)),
  ]);
  if (child.exitCode === null) {
    child.kill("SIGKILL");
    await new Promise((resolve) => child.once("exit", resolve));
  }
}

function writeJson(response, statusCode, value) {
  response.writeHead(statusCode, {
    "Cache-Control": "no-store",
    "Content-Type": "application/json; charset=utf-8",
  });
  response.end(`${JSON.stringify(value, null, 2)}\n`);
}

