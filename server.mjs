async function runLegacyLocalMode() {
  const port = Number(process.env.PORT || 8080);
  const env = paperclipEnvironment({ port, databaseUrl: process.env.DATABASE_URL });
  delete env.DATABASE_URL;
  const child = spawnPaperclip(env);
  for (const signal of ["SIGINT", "SIGTERM"]) {
    process.on(signal, () => child.kill(signal));
  }
  child.on("exit", (code, signal) => {
    if (signal) process.kill(process.pid, signal);
    process.exit(code ?? 1);
  });
}

async function runEntityMode() {
  const publicPort = Number(process.env.PORT || 8080);
  const status = {
    ok: false,
    storageBackend: "omnira-entity-blockstore",
    entityServiceUrl:
      process.env.OMNIRA_ENTITY_URL ||
      "https://entityservice-k4u67azzg5.app.omnira.dev",
    namespace: process.env.OMNIRA_ENTITY_NAMESPACE || "paperclip",
    instanceId,
    mode: "starting",
    holder: process.env.BAD_DEVICE_ENTITY_ID || `${hostname()}:${process.pid}`,
    publicUrl,
    backupIntervalSeconds: Math.max(
      15,
      Number(process.env.OMNIRA_ENTITY_BACKUP_INTERVAL_SECONDS || 60),
    ),
    leaseTtlSeconds: Math.max(
      20,
      Number(process.env.OMNIRA_ENTITY_LEASE_TTL_SECONDS || 45),
    ),
    lastDatabaseSnapshot: null,
    lastRuntimeSnapshot: null,
    lastBackupReason: null,
    lastBackupError: null,
    updatedAt: new Date().toISOString(),
  };

  let upstreamPort = null;
  let child = null;
  let postgres = null;
  let lease = null;
  let runtimeStore = null;
  let backupTimer = null;
  let renewTimer = null;
  let standbyTimer = null;
  let backupPromise = null;
  let transitionRunning = false;
  let expectedChildExit = false;
  let stopping = false;

  const updateStatus = (changes) => {
    Object.assign(status, changes, { updatedAt: new Date().toISOString() });
  };

  const proxyServer = createServer((request, response) => {
    if (request.url === "/_omnira/storage" || request.url?.startsWith("/_omnira/storage?")) {
      writeJson(response, status.ok ? 200 : 503, status);
      return;
    }
    if (!upstreamPort) {
      if ((request.headers.accept || "").includes("text/html")) {
        response.writeHead(503, {
          "Cache-Control": "no-store",
          "Content-Type": "text/html; charset=utf-8",
        });
        response.end(renderWaitingPage(status));
      } else {
        writeJson(response, 503, { error: status.error || "Paperclip is not the active leader" });
      }
      return;
    }

    const upstream = httpRequest(
      {
        host: "127.0.0.1",
        port: upstreamPort,
        method: request.method,
        path: request.url,
        headers: request.headers,
      },
      (upstreamResponse) => {
        response.writeHead(upstreamResponse.statusCode || 502, upstreamResponse.headers);
        upstreamResponse.pipe(response);
      },
    );
    upstream.on("error", (error) => {
      if (!response.headersSent) writeJson(response, 502, { error: error.message });
      else response.destroy(error);
    });
    request.pipe(upstream);
  });

  proxyServer.on("upgrade", (request, socket, head) => {
    if (!upstreamPort) {
      socket.destroy();
      return;
    }
    const upstream = httpRequest({
      host: "127.0.0.1",
      port: upstreamPort,
      method: request.method,
      path: request.url,
      headers: request.headers,
    });
    upstream.on("upgrade", (response, upstreamSocket, upstreamHead) => {
      const headers = Object.entries(response.headers)
        .flatMap(([name, value]) =>
          Array.isArray(value) ? value.map((item) => `${name}: ${item}`) : [`${name}: ${value}`],
        )
        .join("\r\n");
      socket.write(`HTTP/1.1 ${response.statusCode} ${response.statusMessage}\r\n${headers}\r\n\r\n`);
      if (head.length) upstreamSocket.write(head);
      if (upstreamHead.length) socket.write(upstreamHead);
      upstreamSocket.pipe(socket).pipe(upstreamSocket);
    });
    upstream.on("error", () => socket.destroy());
    upstream.end();
  });

  await new Promise((resolve, reject) => {
    proxyServer.once("error", reject);
    proxyServer.listen(publicPort, "0.0.0.0", resolve);
  });
  console.log(`[paperclip-omnira] public proxy listening on :${publicPort}`);

  const apiKey = process.env.OMNIRA_ENTITY_API_KEY;
  const ownerEntityId = process.env.OMNIRA_ENTITY_OWNER_ID;
  if (!apiKey || !ownerEntityId) {
    updateStatus({
      mode: "error",
      error:
        "OMNIRA_ENTITY_API_KEY and OMNIRA_ENTITY_OWNER_ID are required for Entity Service storage",
    });
    return;
  }

  const client = new EntityStoreClient({
    baseUrl: status.entityServiceUrl,
    apiKey,
    namespace: status.namespace,
    ownerEntityId,
  });
  const keyPrefix = `paperclip/instances/${instanceId}`;
  lease = new EntityLease({
    client,
    key: `${keyPrefix}/leader.json`,
    holder: status.holder,
    ttlMs: status.leaseTtlSeconds * 1000,
  });
  const databaseSnapshots = new EntitySnapshotStore({
    client,
    keyPrefix: `${keyPrefix}/database`,
  });
  const runtimeSnapshots = new EntitySnapshotStore({
    client,
    keyPrefix: `${keyPrefix}/runtime`,
  });
  runtimeStore = new EntityRuntimeStore({
    paperclipHome,
    instanceId,
    snapshotStore: runtimeSnapshots,
  });

  const performBackup = async (reason) => {
    if (!postgres) return null;
    if (backupPromise) return backupPromise;
    updateStatus({ backupState: "running", lastBackupReason: reason, lastBackupError: null });
    backupPromise = (async () => {
      const databaseSnapshot = await postgres.backup();
      const runtimeSnapshot = await runtimeStore.backup();
      updateStatus({
        backupState: "idle",
        lastDatabaseSnapshot: databaseSnapshot,
        lastRuntimeSnapshot: runtimeSnapshot,
        lastBackupAt: new Date().toISOString(),
      });
      return databaseSnapshot;
    })();
    try {
      return await backupPromise;
    } catch (error) {
      updateStatus({ backupState: "error", lastBackupError: error.message });
      throw error;
    } finally {
      backupPromise = null;
    }
  };

  const clearLeaderTimers = () => {
    if (backupTimer) clearInterval(backupTimer);
    if (renewTimer) clearInterval(renewTimer);
    backupTimer = null;
    renewTimer = null;
  };

  const stopLeader = async ({ finalBackup = false, release = false } = {}) => {
    clearLeaderTimers();
    upstreamPort = null;
    if (finalBackup && postgres) {
      try {
        await performBackup("graceful-shutdown");
      } catch (error) {
        console.error(`[paperclip-omnira] final backup failed: ${error.message}`);
      }
    }
    if (child && child.exitCode === null) {
      expectedChildExit = true;
      await terminateChild(child);
    }
    child = null;
    if (postgres) {
      await postgres.stop();
      postgres = null;
    }
    if (release && lease) {
      try {
        await lease.release();
      } catch (error) {
        console.error(`[paperclip-omnira] lease release failed: ${error.message}`);
      }
    }
  };

  const enterStandby = async (reason) => {
    if (stopping) return;
    updateStatus({ ok: false, mode: "standby", standbyReason: reason, leaseExpiresAt: null });
    clearLeaderTimers();
    upstreamPort = null;
    if (!standbyTimer) {
      standbyTimer = setInterval(() => void tryLeadership(), 5_000);
    }
  };

  const becomeLeader = async () => {
    updateStatus({
      ok: false,
      mode: "restoring",
      error: null,
      standbyReason: null,
      leaseExpiresAt: lease.expiresAt,
    });
    const restoredRuntime = await runtimeStore.restoreLatest();
    updateStatus({ restoredRuntimeSnapshot: restoredRuntime });

    const usedPorts = new Set([publicPort]);
    const databasePort = Number(process.env.PAPERCLIP_POSTGRES_PORT) ||
      (await findFreePort(usedPorts));
    usedPorts.add(databasePort);
    const appPort = Number(process.env.PAPERCLIP_INTERNAL_PORT) ||
      (await findFreePort(usedPorts));

    postgres = new EntityBackedPostgres({
      dataDir: join(paperclipHome, ".entity-postgres", instanceId),
      port: databasePort,
      snapshotStore: databaseSnapshots,
      onLog: (message) => {
        if (process.env.OMNIRA_ENTITY_POSTGRES_LOGS === "1") console.log(message);
      },
      onError: (message) => console.error(message),
    });
    const databaseUrl = await postgres.start();
    ensureOmniraConfig({ appPort, databaseUrl });
    updateStatus({
      mode: "starting-paperclip",
      restoredDatabaseSnapshot: postgres.lastSnapshot,
    });

    child = spawnPaperclip(paperclipEnvironment({ port: appPort, databaseUrl }));
    expectedChildExit = false;
    child.once("exit", (code, signal) => {
      if (expectedChildExit || stopping) return;
      console.error(
        `[paperclip-omnira] Paperclip exited unexpectedly (${signal || code})`,
      );
      updateStatus({ ok: false, mode: "error", error: "Paperclip exited unexpectedly" });
      void stopLeader({ finalBackup: true, release: true })
        .then(() => enterStandby("Paperclip process exited"))
        .catch((error) => updateStatus({ mode: "error", error: error.message }));
    });
    await waitForHealth(appPort, child);
    upstreamPort = appPort;
    updateStatus({
      ok: true,
      mode: "leader",
      leaseExpiresAt: lease.expiresAt,
      paperclipHealth: "ok",
      databaseEngine: "embedded-postgres",
      durableStore: "Omnira Entity Service BlockStore",
    });
    console.log("[paperclip-omnira] leader is healthy; Entity Service persistence active");

    await performBackup("leader-startup");
    backupTimer = setInterval(() => {
      void performBackup("interval").catch((error) =>
        console.error(`[paperclip-omnira] interval backup failed: ${error.message}`),
      );
    }, status.backupIntervalSeconds * 1000);
    renewTimer = setInterval(() => {
      void lease.renew()
        .then(async (renewed) => {
          if (renewed) {
            updateStatus({ leaseExpiresAt: lease.expiresAt });
            return;
          }
          updateStatus({ ok: false, mode: "demoting", error: "Entity lease was lost" });
          await stopLeader({ finalBackup: false, release: false });
          await enterStandby("Entity lease was lost");
        })
        .catch(async (error) => {
          updateStatus({ leaseRenewalError: error.message });
          console.error(`[paperclip-omnira] lease renewal failed: ${error.message}`);
          updateStatus({ ok: false, mode: "demoting", error: "Entity lease renewal failed" });
          await stopLeader({ finalBackup: false, release: false });
          await enterStandby("Entity lease renewal failed");
        });
    }, Math.floor((status.leaseTtlSeconds * 1000) / 3));
  };

  async function tryLeadership() {
    if (transitionRunning || stopping || status.mode === "leader") return;
    transitionRunning = true;
    try {
      const acquired = await lease.acquire();
      if (!acquired) {
        const current = await client.getJsonOptional(`${keyPrefix}/leader.json`);
        updateStatus({
          ok: false,
          mode: "standby",
          activeHolder: current?.value?.holder ?? null,
          leaseExpiresAt: current?.value?.expiresAt ?? null,
          error: null,
        });
        return;
      }
      if (standbyTimer) clearInterval(standbyTimer);
      standbyTimer = null;
      await becomeLeader();
    } catch (error) {
      console.error(`[paperclip-omnira] leadership transition failed: ${error.stack || error}`);
      updateStatus({ ok: false, mode: "error", error: error.message });
      await stopLeader({ finalBackup: false, release: true }).catch(() => {});
      if (!standbyTimer && !stopping) {
        standbyTimer = setInterval(() => void tryLeadership(), 10_000);
      }
    } finally {
      transitionRunning = false;
    }
  }

  const shutdown = async (signal) => {
    if (stopping) return;
    stopping = true;
    if (standbyTimer) clearInterval(standbyTimer);
    updateStatus({ ok: false, mode: "stopping", shutdownSignal: signal });
    await stopLeader({ finalBackup: true, release: true });
    proxyServer.closeIdleConnections?.();
    const closed = new Promise((resolve) => proxyServer.close(resolve));
    await Promise.race([closed, new Promise((resolve) => setTimeout(resolve, 2_000))]);
    proxyServer.closeAllConnections?.();
    process.exit(0);
  };

  for (const signal of ["SIGINT", "SIGTERM"]) {
    process.on(signal, () => void shutdown(signal));
  }

  await tryLeadership();
  if (status.mode !== "leader" && !standbyTimer) {
    await enterStandby("Another Omnira device holds the Entity lease");
  }
}

const storageBackend = process.env.PAPERCLIP_STORAGE_BACKEND || "omnira-entity";
if (storageBackend === "local") {
  await runLegacyLocalMode();
} else if (storageBackend === "omnira-entity") {
  await runEntityMode();
} else {
  throw new Error(`Unsupported PAPERCLIP_STORAGE_BACKEND: ${storageBackend}`);
}
