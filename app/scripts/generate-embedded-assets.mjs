import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const generatedDir = join(appDir, "generated");
const migrationsDir = join(appDir, "node_modules", "@paperclipai", "db", "dist", "migrations");
const uiDir = join(appDir, "node_modules", "@paperclipai", "server", "ui-dist");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if (entry.isFile()) files.push(path);
  }
  return files;
}

function importPath(fromDirectory, filePath) {
  const value = relative(fromDirectory, filePath).split(sep).join("/");
  return value.startsWith(".") ? value : `./${value}`;
}

const journal = JSON.parse(await readFile(join(migrationsDir, "meta", "_journal.json"), "utf8"));
const uiFiles = await walk(uiDir);
const lines = [
  "// Generated by scripts/generate-embedded-assets.mjs. Do not edit by hand.",
];

for (const [index, entry] of journal.entries.entries()) {
  const path = join(migrationsDir, `${entry.tag}.sql`);
  lines.push(`import migration${index} from ${JSON.stringify(importPath(generatedDir, path))} with { type: "text" };`);
}
for (const [index, path] of uiFiles.entries()) {
  lines.push(`import uiAsset${index} from ${JSON.stringify(importPath(generatedDir, path))} with { type: "file" };`);
}

lines.push("", "export const EMBEDDED_MIGRATIONS = [");
for (const [index, entry] of journal.entries.entries()) {
  lines.push(`  { tag: ${JSON.stringify(entry.tag)}, when: ${Number(entry.when)}, sql: migration${index} },`);
}
lines.push("];", "", "export const EMBEDDED_UI_ASSETS = [");
for (const [index, path] of uiFiles.entries()) {
  const publicPath = `/${relative(uiDir, path).split(sep).join("/")}`;
  lines.push(`  { publicPath: ${JSON.stringify(publicPath)}, embeddedPath: uiAsset${index} },`);
}
lines.push("];");

await mkdir(generatedDir, { recursive: true });
const outputPath = join(generatedDir, "embedded-assets.mjs");
await writeFile(outputPath, `${lines.join("\n")}\n`);
console.log(JSON.stringify({
  outputPath,
  migrations: journal.entries.length,
  uiAssets: uiFiles.length,
}));
